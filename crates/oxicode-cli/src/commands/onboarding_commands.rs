#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::Arc;

    fn make_ctx() -> CommandContext {
        CommandContext {
            state_store: Arc::new(oxicode_state::StateStore::default()),
            model: "test".to_string(),
            provider_name: "test".to_string(),
            session_id: "test".to_string(),
        }
    }

    #[test]
    fn test_mask_key_long() {
        assert_eq!(mask_key("sk-ant-abcdef1234567890"), "sk-ant-...7890");
    }

    #[test]
    fn test_mask_key_short() {
        assert_eq!(mask_key("abc"), "****");
    }

    #[test]
    fn test_default_model_anthropic() {
        // anthropic falls through to the default arm
        assert_eq!(default_model("anthropic"), "claude-sonnet-4-20250514");
        assert_eq!(default_model("unknown"), "claude-sonnet-4-20250514");
    }

    #[test]
    fn test_default_model_openai() {
        assert_eq!(default_model("openai"), "gpt-4o");
    }

    #[test]
    fn test_default_model_ollama() {
        assert_eq!(default_model("ollama"), "llama3.1");
    }

    #[test]
    fn test_sample_toml_contains_fields() {
        let toml = sample_toml("anthropic", "claude-sonnet-4-20250514", "default");
        assert!(toml.contains("provider = \"anthropic\""));
        assert!(toml.contains("model = \"claude-sonnet-4-20250514\""));
        assert!(toml.contains("permission_mode = \"default\""));
    }

    #[test]
    fn test_quick_start_tips_not_empty() {
        let tips = quick_start_tips();
        assert!(tips.contains("/help"));
        assert!(tips.contains("/model"));
    }

    #[test]
    fn test_onboarding_command_metadata() {
        let cmd = OnboardingCommand;
        assert_eq!(cmd.name(), "onboarding");
        assert!(!cmd.description().is_empty());
    }

    #[test]
    fn test_onboarding_command_executes() {
        // This test may create settings.toml or say "already configured".
        // Both are valid outcomes.
        let cmd = OnboardingCommand;
        let ctx = make_ctx();
        let output = cmd.execute("--skip-validation", &ctx);
        match output {
            CommandOutput::Message(msg) | CommandOutput::Error(msg) => assert!(!msg.is_empty()),
            _ => panic!("Expected message or error"),
        }
    }
}
